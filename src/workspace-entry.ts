import { native } from "@hworktime/ui";
import "./catalog";
import { createApp } from "vue";
import Workspace from "./WorkWorkspace.vue";
import { installUI } from "./ui";
import { renderGameMenu, mountGameToolbar } from "./games/menu";
import { mountTyping } from "./typing/mount";
import { mountVocabularyNavigation } from "./vocabulary/mount";
import { createWorkspaceSelect } from "./workspace/select";
import { mountPlayback } from "./music/playback";
import { mountToolDirectory } from "./tools/mount";
import { renderAnalysisSidebar } from "./analysis/sidebar";
import { renderAnalysisMetrics, afterAnalysisRender } from "./analysis/metrics";
import { confirmations } from "./imports/confirmations";
import { mountMusicToolbar, mountMusicTransport } from "./media/mount";
import { createRestartPrompt } from "./games/restart";
import { createMediaSelectGroup } from "./media/selects";
import { archiveView } from "./games/archive";
import { records } from "./imports/records";
export function mountWorkspace() {
  WorkTimeApp.ui.native = native;
  WorkTimeApp.ui.renderAnalysisSidebar = renderAnalysisSidebar;
  WorkTimeApp.ui.renderAnalysisMetrics = renderAnalysisMetrics;
  WorkTimeApp.ui.afterAnalysisRender = afterAnalysisRender;
  WorkTimeApp.ui.confirmations = confirmations;
  WorkTimeApp.ui.loadReaderToolbar = async () =>
    (await import("./media/reader-entry")).mountReaderToolbar;
  WorkTimeApp.ui.mountMusicToolbar = mountMusicToolbar;
  WorkTimeApp.ui.createRestartPrompt = createRestartPrompt;
  WorkTimeApp.ui.createMediaSelectGroup = createMediaSelectGroup;
  WorkTimeApp.ui.archiveView = archiveView;
  WorkTimeApp.ui.importRecords = records;
  WorkTimeApp.ui.mountGameToolbar = mountGameToolbar;
  WorkTimeApp.ui.mountMusicTransport = mountMusicTransport;
  WorkTimeApp.ui.createSelect = createWorkspaceSelect;
  WorkTimeApp.ui.mountVocabularyNavigation = mountVocabularyNavigation;
  WorkTimeApp.ui.mountPlayback = mountPlayback;
  WorkTimeApp.ui.mountToolDirectory = mountToolDirectory;
  WorkTimeApp.ui.mountTyping = mountTyping;
  WorkTimeApp.ui.renderGameMenu = renderGameMenu;
  const app = createApp(Workspace);
  installUI(app);
  app.mount("#worktime-app");
  WorkTimeApp.i18n.apply();
}
